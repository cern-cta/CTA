#![forbid(unsafe_code)]

//! High-level client library for the CTA frontend gRPC interface.
//!
//! This crate talks to the admin service of the CTA frontend over the generated gRPC bindings of [`cta_protobuf`].
//!
//! | Module | Description |
//! | ------ | ----------- |
//! | [`admin`] | `cta-admin-api`: [`admin::AdminClient`], the typed admin commands ([`admin::commands`]), and [`admin::AdminError`] |
//! | [`types`] | Domain types built from the protobuf records ([`types::File`], [`types::Checksum`], [`types::ChecksumType`]) |
//! | [`errors`] | Errors of the conversions into the domain types ([`errors::ChecksumTypeError`], ...) |
//!
//! The macros defining the admin commands ([`macro@typed_admin_cmd`], [`admin_cmd!`]) are exported at the root of the
//! crate.
//!
//! # Example
//!
//! Sending a typed command, to get the protobuf records:
//!
//! ```no_run
//! use cta_client::admin::AdminClient;
//! use cta_client::admin::commands::recycle_tape_file;
//! use tokio_stream::StreamExt;
//!
//! # async fn example(client: AdminClient) -> Result<(), Box<dyn std::error::Error>> {
//! let mut items = client.stream(recycle_tape_file::Ls::default()).await?;
//! while let Some(item) = items.next().await {
//!     let item = item?; // a `RecycleTapeFileLsItem`
//!     println!("{} {}", item.vid, item.disk_file_path);
//! }
//! # Ok(())
//! # }
//! ```

#![warn(missing_docs)]

// The code generated by `#[typed_admin_cmd]` refers to `::cta_client`, also within this crate.
extern crate self as cta_client;

pub mod admin;
