//! Domain model of the CTA catalogue and scheduler (the business objects), and its mapping to and from the protobuf
//! messages of `cta-protobuf`. Independent of the gRPC transport: connecting to the frontend is done by `cta-client`.
//!
//! One type per resource (tape pools, tapes, drives, files, ...), built from the protobuf records of the streaming
//! commands with `TryFrom` (a [`TapePool`](tape::TapePool) from a `TapePoolLsItem`, ...). The conversions give the records their
//! meaning: timestamps become [`Timestamp`](jiff::Timestamp), durations [`Duration`](std::time::Duration), empty
//! strings standing for "none" become `None`, states become enums, and the creation / modification logs are folded into
//! a [`Metadata`]. A record that cannot be converted gives a [`ConversionError`].
//!
//! The types are grouped by domain, and only reachable through their domain module (`cta_model::tape::TapePool`):
//!
//! | Module             | Resources                                                            |
//! |--------------------|----------------------------------------------------------------------|
//! | [`admin`]          | admin users, virtual organisations, versions                         |
//! | [`tape`]           | tapes, tape pools, media types                                       |
//! | [`file`](mod@file) | archived files, their tape and disk metadata, checksums, recycle bin |
//! | [`library`]        | drives, logical and physical libraries                               |
//! | [`routing`]        | storage classes, archive routes, mount policies, mount rules         |
//! | [`disk`]           | disk instances, disk instance spaces, disk systems                   |
//! | [`scheduler`]      | user request queues, failed requests, repack requests                |
//! | [`events`]         | workflow events a disk system notifies CTA of, and their encoding    |
//!
#![warn(missing_docs)]

